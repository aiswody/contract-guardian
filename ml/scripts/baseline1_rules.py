CAUTION = [
    r"원상복구|원상회복|입주.{0,8}(당시|시점|때).{0,8}상태",
    r"별도",
    r"(협의|상의)",
    r"(임차인|세입자|을)(이|은|의|가)?\s*.{0,15}(부담|수리|비용|낸다|몫|책임)",
    r"(확인하였|확인했|확인한다|고지한다|고지하였)",
    r"위약금|중개보수|중개수수료",
    r"청소비|청소",
    r"세대수|세대별|세대 수",
    r"통보|통지",
    r"유보|공제",
    r"(변동|조정|재산정|인상)될 수 있",
    r"근저당|선순위",
    r"동의 없이|허가|승인",
    r"관리\s*규정|안내에 따",
]


def classify(text):
    for pat in DANGER:
        if re.search(pat, text):
            return "danger"
    for pat in SAFE:
        if re.search(pat, text):
            return "safe"
    for pat in CAUTION:
        if re.search(pat, text):
            return "caution"
    return "safe"


def main():
    for split in ("train", "val"):
        texts, y_true, _ = load_split(split)
        y_pred = [classify(t) for t in texts]
        report(f"Baseline 1 (규칙) — {split}", y_true, y_pred)


if __name__ == "__main__":
    main()
