    r"(모든|일체|전부|여하한|각종|제반)\s*.{0,15}(수리|시설물|유지|보수|비용|책임|하자|이의|민원)",
    r"(통상|마모).{0,10}(포함)",
    r"(새것|신품|새 제품)으?로?\s*.{0,8}(교체|바꿔|바꾸)",
    r"(언제든|수시로)",
    r"(즉시|곧바로|바로)\s*.{0,6}(해지|퇴거|계약 해지)",
    r"(통보|예고|최고)\s*(절차\s*)?없이",
    r"자동\s*.{0,6}(인상|종료|적용|오른다)",
    r"(몰취|반환하지 않|돌려주지 않|반환은.{0,15}유예)",
    r"(단전|단수|전기와 수도를 끊|공급이 중단)",
    r"임의로?\s*.{0,8}(반출|들어내|옮길)",
    r"(새|다음|신규|후속)\s*(임차인|세입자).{0,25}(까지|입주|구해|계약금 수령)",
    r"제소전화해",
    r"(특약|본 특약).{0,12}(우선)",
    r"보증금의\s*\d+\s*(%|퍼센트)",
    r"\d+개월분.{0,10}(월세|차임).{0,10}위약금",
    r"무조건",
    r"(지연\s*이자|이자).{0,15}(발생하지 않|부담하지 않|붙지 않|청구하지 않)",
