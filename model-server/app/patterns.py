"""판정 근거 패턴 — 결과의 reason 필드용 (스펙 §4.3 "왜 이런 판정인지").

라벨링 가이드라인 §2.1·경계 사례집(docs/labeling-guideline.md)에서 추린
대표 위험 신호. 분류는 모델이 하고, 이 패턴은 근거 설명과 6주차 LLM 컨텍스트에만
쓰인다 (패턴 미일치여도 모델 판정은 유효).
"""
import re

RISK_SIGNALS: list[tuple[str, re.Pattern]] = [
    ("법정 권리 포기·이의 제기 금지", re.compile(
        r"(포기|이의를?\s*.{0,10}(제기하지|달지)\s*않|문제\s*삼지\s*않|행사하지\s*않|신청하지\s*않)")),
    ("전입신고·확정일자 제한 (대항력 위협)", re.compile(
        r"(전입신고|확정일자|임차권등기).{0,25}(하지\s*않|아니한|이후|다음\s*주|금지)")),
    ("임대인 일방 결정(백지위임)", re.compile(
        r"(임대인|집주인|갑)(이|의)?\s*.{0,10}(정하|결정|판단|재량|수시로)")),
    ("포괄·무제한 부담 전가", re.compile(
        r"(모든|일체|전부|여하한|제반|각종)\s*.{0,15}(수리|비용|책임|시설|하자|유지|보수)")),
    ("통상 마모 초과 원상복구 요구", re.compile(
        r"(통상|마모).{0,10}포함|(새것|신품|새\s*제품).{0,10}(교체|바꾸)")),
    ("일방 해지·즉시 퇴거", re.compile(
        r"(언제든|통보\s*없이|예고\s*없이|즉시|곧바로|바로)\s*.{0,8}(해지|퇴거)")),
    ("보증금 반환 조건부·지연", re.compile(
        r"(새|다음|신규|후속)\s*(임차인|세입자).{0,20}(까지|입주|구해)|자금\s*사정|반환하지\s*않|몰취")),
    ("자동 인상·자동 종료 간주", re.compile(r"자동\s*.{0,8}(인상|종료|적용|오른)")),
    ("사적 실력 행사(단전·단수·임의 반출)", re.compile(r"단전|단수|임의로?\s*.{0,8}(반출|들어내|옮길)|끊을 수")),
    ("제소전화해 강제", re.compile(r"제소전화해")),
    ("법령 배제 시도", re.compile(r"특약.{0,12}우선|법령.{0,15}우선")),
    ("신탁·무권한 계약 위험", re.compile(r"신탁|수탁사?")),
    ("금액·항목 미명시", re.compile(r"별도(로)?\s*(한다|부과|조건)?\.?$")),
    ("협의·추후 위임(불확정)", re.compile(r"(추후|향후|나중에)?\s*협의|상의해서|안내에 따")),
]


def find_signals(text: str, limit: int = 2) -> list[str]:
    """문장에서 감지된 위험 신호 라벨을 최대 limit개 반환."""
    return [name for name, pat in RISK_SIGNALS if pat.search(text)][:limit]
