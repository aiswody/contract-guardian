    r"(포기|행사하지 않|신청하지 않|신청은 하지 않|신청 권리를 행사하지)",
    r"(이의|이의를)\s*.{0,12}(제기하지 않|제기하지 아니|달지 않|없이 동의|없이 지급)",
    r"문제\s*삼지\s*않",
    r"전입신고.{0,20}(하지 않|하지 아니|안 하)",
    r"확정일자.{0,25}(이후에|뒤에|받지 않|하지 않)",
    r"(임대인|집주인|갑)(이|의)\s*.{0,8}(정하|결정|판단|재량)",
